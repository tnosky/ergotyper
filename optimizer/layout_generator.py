import re
import random
import math
import numpy as np
from collections import Counter
import os

# config
LOG_FILE = "ergo_log.txt"
CORPUS_FILE = "tf_corpus.txt"
EPOCHS = 1000  # training epochs
BATCH_SIZE = 32 # variations per step
LEARNING_RATE = 0.1 # concept for step size
LAYERS = 3 # optimization passes per epoch

# weights
TEXT_INFLUENCE = 0.85
PHYSICAL_INFLUENCE = 0.15

def download_corpus():
    print("Downloading TF dataset...")
    try:
        import tensorflow_datasets as tfds
        import tensorflow as tf

        # simple-103 dataset
        ds = tfds.load('wikitext/wikitext-2-v1', split='train', shuffle_files=False)

        print("Processing...")
        full_text = ""
        # 5000 examples
        for example in ds.take(5000):
            text = example['text'].numpy().decode('utf-8')
            full_text += text + " "

        with open(CORPUS_FILE, "w", encoding="utf-8") as f:
            f.write(full_text)

        print(f"Saved {len(full_text)} chars.\n")
        return True
    except Exception as e:
        print(f"Download failed: {e}")
        return False

def parse_hand_data(log_file):
    key_positions = {}

    with open(log_file, 'r') as f:
        for line in f:
            match = re.search(r"Key=([A-Z]),.*Left=([\d\.]+),([\d\.]+),.*Right=([\d\.]+),([\d\.]+)", line)
            if match:
                key = match.group(1)
                lx, ly = float(match.group(2)), float(match.group(3))
                rx, ry = float(match.group(4)), float(match.group(5))

                if key in "QWERTASDFGZXCVB":
                    pos = (lx, ly)
                else:
                    pos = (rx, ry)

                if key not in key_positions:
                    key_positions[key] = []
                key_positions[key].append(pos)

    avg_positions = {}
    for key, positions in key_positions.items():
        avg_x = sum(p[0] for p in positions) / len(positions)
        avg_y = sum(p[1] for p in positions) / len(positions)
        avg_positions[key] = (avg_x, avg_y)

    return avg_positions

def calculate_cost(layout_list, text_counts, physical_map):
    total_cost = 0
    char_to_index = {char: i for i, char in enumerate(layout_list)}
    qwerty_template = "QWERTYUIOPASDFGHJKLZXCVBNM"

    slot_coords = {}
    for i, char in enumerate(qwerty_template):
        if char in physical_map:
            slot_coords[i] = physical_map[char]
        else:
            row = 0 if i < 10 else (1 if i < 19 else 2)
            col = i if row == 0 else (i-10 if row == 1 else i-19)
            slot_coords[i] = (col * 50, row * 50)

    for bigram, count in text_counts.items():
        if len(bigram) != 2: continue
        char1, char2 = bigram[0], bigram[1]

        if char1 not in char_to_index or char2 not in char_to_index: continue

        idx1 = char_to_index[char1]
        idx2 = char_to_index[char2]

        pos1 = slot_coords.get(idx1, (0,0))
        pos2 = slot_coords.get(idx2, (0,0))

        dist = math.sqrt((pos1[0]-pos2[0])**2 + (pos1[1]-pos2[1])**2)

        weighted_count = count * (TEXT_INFLUENCE / (1 - TEXT_INFLUENCE))
        total_cost += dist * weighted_count

    return total_cost

def generate_layout_ml(initial_map):

    # load corpus
    try:
        with open(CORPUS_FILE, 'r', encoding='utf-8') as f:
            text = f.read().upper()
    except FileNotFoundError:
        print("Missing corpus. Downloading...")
        if download_corpus():
            with open(CORPUS_FILE, 'r', encoding='utf-8') as f:
                text = f.read().upper()

    bigrams = [text[i:i+2] for i in range(len(text)-1) if text[i:i+2].isalpha()]
    bigram_counts = Counter(bigrams)

    # Input Layer
    current_layout = list("QWERTYUIOPASDFGHJKLZXCVBNM")
    random.shuffle(current_layout)

    current_loss = calculate_cost(current_layout, bigram_counts, initial_map)
    best_layout = current_layout[:]
    best_loss = current_loss

    print(f"Start Training: {EPOCHS} Epochs, Batch {BATCH_SIZE}")
    print("-" * 40)

    for epoch in range(EPOCHS):
        # LR decay
        lr = max(0.01, min(1, 1 - float(epoch) / EPOCHS))

        # Forward Pass
        for layer in range(LAYERS):

            # Batch Processing
            batch_candidates = []
            for _ in range(BATCH_SIZE):
                candidate_layout = current_layout[:]

                # Apply Filters (Mutations)
                # Layer 0: Local swaps
                # Layer 1: Random shuffles
                # Layer 2: Focused opt
                if layer == 0:
                    idx1, idx2 = random.sample(range(26), 2)
                    candidate_layout[idx1], candidate_layout[idx2] = candidate_layout[idx2], candidate_layout[idx1]
                elif layer == 1:
                    if random.random() < 0.3:
                        random.shuffle(candidate_layout)
                else: # Layer 2
                     idx1 = random.randint(0, 25)
                     idx2 = (idx1 + 1) % 26
                     candidate_layout[idx1], candidate_layout[idx2] = candidate_layout[idx2], candidate_layout[idx1]

                loss = calculate_cost(candidate_layout, bigram_counts, initial_map)
                batch_candidates.append((loss, candidate_layout))

            # Gradient calc
            batch_candidates.sort(key=lambda x: x[0])
            best_batch_loss, best_batch_layout = batch_candidates[0]

            # Backprop / Update
            loss_delta = best_batch_loss - current_loss

            # Update rule
            if loss_delta < 0 or random.random() < math.exp(-loss_delta / (lr * 1000)):
                current_layout = best_batch_layout
                current_loss = best_batch_loss

                if current_loss < best_loss:
                    best_loss = current_loss
                    best_layout = current_layout[:]

        print(f"Epoch {epoch+1}/{EPOCHS} | Loss: {int(current_loss)} | Best: {int(best_loss)}")

    return "".join(best_layout)

