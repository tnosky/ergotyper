# install libraries
# !pip install -q ultralytics roboflow

from ultralytics import YOLO
from roboflow import Roboflow
import os
import yaml
import glob

# config
ROBOFLOW_API_KEY = os.environ["ROBOFLOW_API_KEY"]
WORKSPACE_NAME = "ece528-project"
PROJECT_NAME = "keyboard-ip59o"
VERSION_NUMBER = 2

# download dataset
print("Downloading dataset from Roboflow...")
rf = Roboflow(api_key=ROBOFLOW_API_KEY)
project = rf.workspace(WORKSPACE_NAME).project(PROJECT_NAME)
version = project.version(VERSION_NUMBER)
dataset = version.download("yolov8")

print(f"Dataset downloaded to: {dataset.location}")

# fix data.yaml
yaml_path = f"{dataset.location}/data.yaml"

with open(yaml_path, 'r') as f:
    data_config = yaml.safe_load(f)

# check val path
val_path = os.path.join(dataset.location, data_config.get('val', 'valid'))
if not os.path.exists(val_path):
    print("validation folder missing")
    print("pointing validation path to training data")

    # point val to train
    data_config['val'] = data_config['train']

    # save fixed yaml
    with open(yaml_path, 'w') as f:
        yaml.dump(data_config, f)
    print("data.yaml fixed")

# train model
print("Starting training...")
model = YOLO('yolov8n.pt')

# train
model.train(
    data=yaml_path,
    epochs=50,
    imgsz=640,
    plots=True,
    batch=16
)

# export to tflite int8
print("Exporting model to tflite...")
model.export(format='tflite', int8=True)

# locate output
tflite_files = glob.glob('runs/detect/train*/weights/*_int8.tflite')

if tflite_files:
    latest_file = tflite_files[-1]

    print(f"Trained model saved to: {latest_file}")

else:
    print("Export finished but couldn't locate file")